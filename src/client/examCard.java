package client;

public class examCard {

    String cls;
    String sub;
    String topic;
    String dur;
    String mark;

    public examCard(String cls, String sub, String topic, String dur, String mark) {
        this.cls = cls;
        this.sub = sub;
        this.topic = topic;
        this.dur = dur;
        this.mark = mark;
    }

}
